-- PHẦN D — MATERIALIZED VIEW analytics_question
-- Refresh nightly bằng pg_cron (xem hướng dẫn ở cuối file).
-- ============================================================================

drop materialized view if exists public.analytics_question;
create materialized view public.analytics_question as
select
    eq.question_id,
    count(a.id)                                                  as total_attempts,
    count(a.id) filter (where a.is_correct = true)               as total_correct,
    case when count(a.id) > 0
         then round(100.0 * count(a.id) filter (where a.is_correct) / count(a.id), 2)
         else 0 end                                              as correct_rate,
    case when count(a.id) > 0
         then round(100.0 * count(a.id) filter (where a.is_correct = false) / count(a.id), 2)
         else 0 end                                              as error_rate
from public.exam_questions eq
left join public.answers a on a.exam_id = eq.exam_id and a.order_no = eq.order_no
group by eq.question_id;

create unique index if not exists uq_mv_analytics_question
    on public.analytics_question(question_id);


